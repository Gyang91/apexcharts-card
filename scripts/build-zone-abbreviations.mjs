// Generates src/zone-abbreviations.ts: the time zone abbreviations of the IANA
// database (CET, EDT, MSK, +0545...) as eras per zone, taken from
// moment-timezone's data. The card builds offsets and DST dates from the
// browser; only these names cannot come from it.
//
//   npm run build:zone-abbreviations
//
// tests/moment-timezones.test.ts fails when the file is out of date with the
// installed moment-timezone.
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);

// An era starts where a zone renames an offset it already used, so a zone has
// one era for as long as its offsets keep their names (New York: one era since
// 1883 for EST/EDT...). Encoded as "start|offset=abbr,offset=abbr;..." with the
// start in minutes since 1970 (empty: since forever) and offsets in seconds
// east of UTC.
export function buildZoneAbbreviations() {
  const { tz } = require('moment-timezone/moment-timezone');
  const data = require('moment-timezone/data/packed/latest.json');
  const eras = {};
  for (const packed of data.zones) {
    const zone = tz.unpack(packed);
    const out = [];
    let names = null;
    zone.untils.forEach((until, i) => {
      const offset = String(-Math.round(zone.offsets[i] * 60));
      if (!names || (offset in names && names[offset] !== zone.abbrs[i])) {
        names = {};
        out.push([i === 0 ? '' : String(Math.round(zone.untils[i - 1] / 60000)), names]);
      }
      names[offset] = zone.abbrs[i];
    });
    eras[zone.name] = out
      .map(
        ([start, map]) =>
          `${start}|${Object.entries(map)
            .map(([o, a]) => `${o}=${a}`)
            .join(',')}`,
      )
      .join(';');
  }
  const links = {};
  for (const link of data.links) {
    const [target, alias] = link.split('|');
    links[alias] = target;
  }
  return `// Generated by scripts/build-zone-abbreviations.mjs from moment-timezone data
// ${data.version}. Do not edit: run \`npm run build:zone-abbreviations\`.
export const ZONE_ABBREVIATIONS: Record<string, string> = ${JSON.stringify(eras, null, 0)};
export const ZONE_LINKS: Record<string, string> = ${JSON.stringify(links, null, 0)};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = fileURLToPath(new URL('../src/zone-abbreviations.ts', import.meta.url));
  writeFileSync(target, buildZoneAbbreviations());
  console.log(`wrote ${target}`);
}
